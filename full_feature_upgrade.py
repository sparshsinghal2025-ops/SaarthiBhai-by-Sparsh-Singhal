    def _source_catalog(kind: str = "", query: str = "", limit: int = 20) -> list[dict]:
        """Metadata-only source index. A link is official only on an allow-listed HTTPS host."""
        kind = (kind or "").strip().lower()
        query = (query or "").strip().lower()
        catalog = _official_source_seeds()
        try:
            store = getattr(db, "supabase", None)
            if store and store.enabled:
                db_rows = store.select_many(
                    "study_intelligence_sources",
                    ({"kind": f"eq.{kind}"} if kind else {}),
                    limit=250,
                    columns="kind,title,url,institution,domain,status,metadata,last_seen_at,class_name,subject,chapter,published_at",
                )
                for row in db_rows:
                    url = str(row.get("url") or "").strip()
                    title = str(row.get("title") or "").strip()
                    if not url or not title:
                        continue
                    official = _is_official_url(url)
                    meta = row.get("metadata") if isinstance(row.get("metadata"), dict) else {}
                    catalog.append({
                        "kind": str(row.get("kind") or "official"), "title": title[:240], "url": url,
                        "institution": str(row.get("institution") or "External source"),
                        "domain": str(row.get("domain") or urllib.parse.urlparse(url).hostname or ""),
                        "label": "Verified Official" if official else "External Link — not verified",
                        "note": str(meta.get("note") or "Metadata only; open the source page for the original material.")[:500],
                        "class_name": row.get("class_name"), "subject": row.get("subject"),
                        "chapter": row.get("chapter"), "published_at": row.get("published_at"),
                        "metadata_only": True,
                    })
        except Exception:
            pass
        # De-duplicate by exact canonical URL, preferring the curated seed label/note.
        dedup = {}
        for row in catalog:
            key = str(row.get("url") or "").strip().rstrip("/")
            if key and key not in dedup:
                dedup[key] = row
        values = list(dedup.values())
        if kind:
            values = [x for x in values if str(x.get("kind") or "").lower() == kind]
        if query:
            matches = [x for x in values if query in (str(x.get("title", "")) + " " + str(x.get("institution", "")) + " " + str(x.get("note", ""))).lower()]
            # Topic names don't usually appear in broad official index titles; return the official index pages as fallback.
            if matches:
                values = matches
        values.sort(key=lambda x: (x.get("label") != "Verified Official", x.get("kind", ""), x.get("title", "")))
        return values[:max(1, min(int(limit or 20), 100))]

    def _matching_official_source(kind: str, topic: str = "") -> Optional[dict]:
        rows = _source_catalog(kind=kind, query="", limit=30)
        if not rows:
            return None
        # Prefer exact topical title matches; otherwise return the official archive/index, never an invented exact-paper match.
        words = [w for w in re.findall(r"[a-z0-9]{4,}", (topic or "").lower()) if w not in {"class", "chapter", "question", "paper", "exam", "topic"}]
        for row in rows:
            title = str(row.get("title") or "").lower()
            if words and any(w in title for w in words):
                return row
        return rows[0]

    def _supa_patch(table: str, filters: dict, payload: dict) -> bool:
        """Patch only counts as successful when Supabase confirms a row changed."""
        store = getattr(db, "supabase", None)
        if not store or not store.enabled:
            return False
        try:
            headers = dict(store.headers)
            headers["Prefer"] = "return=representation"
            resp = requests.patch(store._url(table), headers=headers, params=filters, json=payload,
                                  timeout=getattr(config, "SUPABASE_TIMEOUT", 5.0))
            if resp.status_code >= 300:
                return False
            changed = resp.json() if resp.content else []
            return isinstance(changed, list) and len(changed) > 0
        except Exception:
            return False

    def _claim_review_item(item_id: str, now: str) -> bool:
        """Atomic pending -> approving claim; protects against double-click publication."""
        store = getattr(db, "supabase", None)
        if not store or not store.enabled:
            return False
        try:
            headers = dict(store.headers)
            headers["Prefer"] = "return=representation"
            resp = requests.patch(
                store._url("study_question_queue"), headers=headers,
                params={"id": f"eq.{item_id}", "status": "eq.pending"},
                json={"status": "approving", "reviewed_at": now},
                timeout=getattr(config, "SUPABASE_TIMEOUT", 5.0),
            )
            if resp.status_code >= 300:
                return False
            changed = resp.json() if resp.content else []
            return isinstance(changed, list) and len(changed) == 1
        except Exception:
            return False

    def _reject_full_copy(text: str) -> Optional[str]:
        raw = (text or "").strip()
        words = re.findall(r"\S+", raw)
        if len(raw) > 1200 or len(words) > 180:
            return "Please submit one short question only (maximum 1,200 characters / 180 words), not a full paper, book chapter or PDF dump."
        if re.search(r"\b(full\s*(book|paper|pdf|textbook)|entire\s*(book|paper|chapter|textbook)|paper\s*leak|exam\s*leak|downloaded\s*textbook|scan\s*of\s*(the\s*)?(whole|entire))\b", raw, re.I):
            return "Full books, full papers, leaked papers and full scans are not accepted. Submit one short question in your own words."
        return None

    def _library_source(question: str, exam: str = "", subject: str = "", source_types: Optional[List[str]] = None) -> Optional[dict]:
        """Return official-link metadata only. Community rows are never labelled official."""
        try:
            rows = db.search_library(question, exam_type=exam, subject=subject, limit=8)
        except Exception:
            rows = []
        allowed = {str(x).strip().lower() for x in (source_types or [])}
        for row in rows:
            st = str(row.get("source_type") or "").strip().lower()
            url = str(row.get("url") or "").strip()
            if (allowed and st not in allowed) or not _is_official_url(url):
                continue
            return {
                "title": str(row.get("title") or "Official source link")[:240],
                "url": url,
                "source_type": st,
                "institution": urllib.parse.urlparse(url).hostname or "Official source",
                "label": "Verified Official",
                "metadata_only": True,
            }
        return None

