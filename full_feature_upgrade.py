    def _is_official_url(url: str) -> bool:
        try:
            parsed = urllib.parse.urlparse(str(url or "").strip())
            host = (parsed.hostname or "").lower().strip(".")
            return parsed.scheme == "https" and any(host == d or host.endswith("." + d) for d in OFFICIAL_HOSTS)
        except Exception:
            return False

